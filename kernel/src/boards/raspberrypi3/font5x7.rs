/// Look up a glyph for a printable ASCII byte, falling back to the space
/// glyph for anything outside 0x20..=0x7E (control bytes not handled
/// upstream by `fbconsole`, stray high-bit bytes, ...).
pub fn glyph(c: u8) -> &'static [u8; 7] {
    if (FIRST_CHAR..=LAST_CHAR).contains(&c) {
        &GLYPHS[(c - FIRST_CHAR) as usize]
    } else {
        &GLYPHS[0]
    }
}
